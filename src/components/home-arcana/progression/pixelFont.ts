const ROWS = 8;

/**
 * The name tag as a canvas, one texel per pixel (shown scaled up, image-rendering:
 * pixelated): white text on a faint black plate, with a texel of plate round it.
 */
export function drawNametag(name: string, plate = 'rgba(0, 0, 0, .25)', ink = '#ffffff'): HTMLCanvasElement {
  const glyphs = [...name].map(ch => G[ch] ?? G['?']);
  const textW = glyphs.reduce((sum, glyph) => sum + glyph[0].length, 0) + Math.max(0, glyphs.length - 1);
  const canvas = document.createElement('canvas');
  canvas.width = textW + 2;
  canvas.height = ROWS + 1;
  const context = canvas.getContext('2d');
  if (!context) return canvas;
  context.fillStyle = plate;
  context.fillRect(0, 0, canvas.width, canvas.height);
  context.fillStyle = ink;
  let x = 1;
  for (const glyph of glyphs) {
    glyph.forEach((row, y) => {
      for (let i = 0; i < row.length; i++) if (row[i] === '#') context.fillRect(x + i, y + 1, 1, 1);
    });
    x += glyph[0].length + 1;
  }
  return canvas;
}
